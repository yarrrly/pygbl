FirmwareImage = Union[GBL3Image, GBL4Image, EBLImage]


def parse_firmware_image(data: bytes, *, validate: bool = True) -> FirmwareImage:
    """Parse a Silicon Labs GBL or EBL firmware image."""
    data = bytes(data)

    if data.startswith(GBL3_MAGIC):
        return GBL3Image.from_bytes(data, validate=validate)

    if data.startswith(GBL4_MAGIC):
        # v4 has no CRC to check, so `validate` does not apply
        return GBL4Image.from_bytes(data)

    if data.startswith(EBL_MAGIC):
        return EBLImage.from_bytes(data, validate=validate)

    raise ParseError("Data is not a GBL or EBL image")


